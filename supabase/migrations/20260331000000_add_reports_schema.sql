-- ─── Status enum ─────────────────────────────────────────────────────────────

CREATE TYPE public.report_status AS ENUM ('in_progress', 'completed');


-- ─── Part I configuration: task templates ────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.task_templates (
  id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text        NOT NULL,
  is_active  boolean     NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

-- Enforces "at most one active template at any time" at the DB layer.
-- Application must set is_active = false on the current active template
-- before activating a new one (or use an UPDATE that toggles both in one txn).
CREATE UNIQUE INDEX task_templates_one_active_idx
  ON public.task_templates (is_active)
  WHERE is_active = true;

CREATE TABLE IF NOT EXISTS public.task_template_items (
  id          bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id bigint  NOT NULL REFERENCES public.task_templates(id) ON DELETE CASCADE,
  position    integer NOT NULL CHECK (position > 0),
  description text    NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT timezone('utc', now())
);


-- ─── Part II configuration: stock items ──────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.stock_items (
