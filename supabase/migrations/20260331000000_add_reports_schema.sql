-- ─── Reports (one per shift) ──────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS public.reports (
  id           bigint               GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_id     bigint               NOT NULL UNIQUE REFERENCES public.shifts(id) ON DELETE RESTRICT,
  status       public.report_status NOT NULL DEFAULT 'in_progress',
  created_at   timestamptz          NOT NULL DEFAULT timezone('utc', now()),
  submitted_at timestamptz,
  submitted_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,

  -- submitted_at must be present iff status is completed.
  -- submitted_by may be NULL even on completed reports (user was deleted after submission).
  CONSTRAINT reports_submitted_consistency CHECK (
    (status = 'in_progress' AND submitted_at IS NULL) OR
    (status = 'completed'   AND submitted_at IS NOT NULL)
  )
);

-- Wire up the pre-existing shifts.report_id column (plain bigint, no FK until now)
ALTER TABLE public.shifts
  ADD CONSTRAINT shifts_report_id_fkey
  FOREIGN KEY (report_id) REFERENCES public.reports(id)
  ON DELETE SET NULL;


-- ─── Part I snapshot + completions ───────────────────────────────────────────

-- Snapshot of task template items taken at report creation.
-- Stores text directly — NOT a FK to task_template_items — so changes to the
-- live template never affect in-progress or completed reports.
CREATE TABLE IF NOT EXISTS public.report_task_items (
  id          bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id   bigint  NOT NULL REFERENCES public.reports(id) ON DELETE CASCADE,
  position    integer NOT NULL CHECK (position > 0),
  description text    NOT NULL
);

-- One row per completed task. A task with no row is incomplete.
-- Deleting the row marks the task unchecked (toggle pattern).
-- completed_by uses SET NULL so historical completions survive user deletion.
CREATE TABLE IF NOT EXISTS public.report_task_completions (
  id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_item_id bigint      NOT NULL UNIQUE REFERENCES public.report_task_items(id) ON DELETE CASCADE,
  completed_by uuid        REFERENCES auth.users(id) ON DELETE SET NULL,
  completed_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);


-- ─── Part II snapshot + entries ──────────────────────────────────────────────

-- Snapshot of stock items taken at report creation.
-- Stores name and unit as text — same snapshot rationale as above.
CREATE TABLE IF NOT EXISTS public.report_stock_items (
  id        bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id bigint  NOT NULL REFERENCES public.reports(id) ON DELETE CASCADE,
  position  integer NOT NULL CHECK (position > 0),
  name      text    NOT NULL,
  unit      text    NOT NULL
);

-- One row per stock snapshot item. A missing row means the bartender has not
-- yet entered a value. All items must have an entry before submission is allowed
-- (enforced at application layer — DB allows null quantity until submission).
CREATE TABLE IF NOT EXISTS public.report_stock_entries (
  id            bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stock_item_id bigint  NOT NULL UNIQUE REFERENCES public.report_stock_items(id) ON DELETE CASCADE,
  quantity      numeric,
  not_relevant  boolean NOT NULL DEFAULT false,

  -- Either a quantity is provided, or the item is marked not relevant.
  -- Both fields may be null/false while the report is in_progress.
  -- Application must enforce all items are resolved before allowing submission.
  CONSTRAINT report_stock_entries_value_check CHECK (
    not_relevant = true OR quantity IS NOT NULL
  )
);


-- ─── Part III snapshot + responses ───────────────────────────────────────────

-- Snapshot of open sections taken at report creation.
CREATE TABLE IF NOT EXISTS public.report_section_items (
